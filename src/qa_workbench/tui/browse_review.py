"""Rows and detail text for the Review page: AI records waiting for a person."""

from qa_workbench.review.service import ReviewService
from qa_workbench.storage.repository import MarkdownRepository
from qa_workbench.tui.browse import BrowseData, BrowseRow, section
from qa_workbench.workspace import review_policies

REVIEW_COLUMNS = ("ID", "Status", "From", "Title")
BODY_LIMIT = 1500


def review_service(repository: MarkdownRepository) -> ReviewService:
    return ReviewService(repository, review_policies())


def pending_count(repository: MarkdownRepository) -> int:
    """How many AI records are waiting for a decision."""
    return len(review_service(repository).pending())


def review_rows(repository: MarkdownRepository) -> BrowseData:
    rows = []
    for record in review_service(repository).pending():
        meta = record.metadata
        status = str(meta["status"])
        source = str(meta.get("generated_by") or "-")
        title = str(meta.get("title") or record.id)
        rows.append(
            BrowseRow(
                record.id,
                (record.id, status, source, title),
                status,
                f"{record.id} {title} {status} {source}".lower(),
            )
        )
    return BrowseData(tuple(rows))


def review_detail(repository: MarkdownRepository, record_id: str) -> str:
    record = repository.get(record_id)
    meta = record.metadata
    lines = [
        f"{record.id}  {meta.get('title', '')}",
        f"Status {meta['status']}   Generated by {meta.get('generated_by') or '-'}   "
        f"Author {meta.get('author') or '-'}",
        "A person must decide. The AI's statements are analysis, not evidence.",
    ]
    findings = meta.get("ai_findings")
    if isinstance(findings, list) and findings:
        shown = []
        for item in findings:
            if not isinstance(item, dict):
                continue
            source = item.get("source")
            cited = f"  [{source}]" if source else "  [no source]"
            shown.append(
                f"{str(item.get('kind', '?')).upper():<14} {item.get('text')}{cited}"
            )
        lines += section("WHAT THE AI SAID", shown)
    reviews = meta.get("reviews")
    if isinstance(reviews, list) and reviews:
        lines += section(
            "EARLIER REVIEWS",
            [
                f"{r.get('decision')} by {r.get('reviewer')}"
                + (f": {r.get('comment')}" if r.get("comment") else "")
                for r in reviews
                if isinstance(r, dict)
            ],
        )
    body = record.body.strip()
    if body:
        clipped = body[:BODY_LIMIT] + ("..." if len(body) > BODY_LIMIT else "")
        lines += ["", clipped]
    return "\n".join(lines)
